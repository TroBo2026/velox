"use strict";
const assert=require("node:assert/strict");
const Wrapped=require("../wrapped-core.js");
const Core=require("../ride-core.js");
const elevation=require("../elevation-core.js");

// Ausschließlich konstruierte Geraden in Metern, ohne Bezug zu einer aufgezeichneten Fahrt.
const lat=50, degree=6371000*Math.PI/180;
const line=(x,y,dx,dy,n)=>Array.from({length:n},(_,i)=>[x+i*dx,y+i*dy]);
function ride(id,year,month,coords,accuracy=5){
  const startedAt=new Date(year,month,1,12).getTime();
  const points=coords.map(([x,y],i)=>({lat:lat+y/degree,lon:12+x/(degree*Math.cos(lat*Math.PI/180)),t:startedAt+i*2000,accuracy}));
  return {id,name:"Testfahrt "+id,startedAt,endedAt:points.at(-1)?.t??startedAt,points};
}
const old=ride("alt",2024,11,line(0,0,10,0,25));
const shifted=ride("versetzt",2025,0,line(240,5,-10,0,25));
const branch=ride("Abzweig",2025,1,[...line(0,0,10,0,13),...line(120,10,0,10,12)]);
const parallel=ride("parallel",2025,3,line(0,35,10,0,25));
const report=(...rides)=>Wrapped.analyzeYear(rides,2025);
const near=(a,b,m=1)=>assert.ok(Math.abs(a-b)<m,`${a} differs from ${b}`);
assert.equal(report(old,shifted).newM,0);
assert.equal(report(old,{...shifted,points:shifted.points.filter((_,i)=>i%3===0)}).newM,0);
near(report(old,branch).newM,120);
near(report(old,parallel).newM,240);
const cross=ride("Kreuzung",2025,2,line(120,-80,0,10,17));
near(report(old,cross).newM,160);
const uncertain=ride("unsicher",2025,0,line(0,14,10,0,25));
near(report(old,uncertain).uncertainM,240);
assert.equal(report(old,uncertain).newM,0);
assert.equal(report(old,ride("ungenau",2025,0,line(0,80,10,0,25),40)).newM,0);
const repeat={...branch,id:"Wiederholung",startedAt:branch.startedAt+86400000};
near(report(repeat,old,branch).newM,120);
const loop=ride("hin-zurück",2025,0,[...line(0,0,10,0,25),...line(230,0,-10,0,24)]);
near(report(loop).newM,240);
const gap=ride("Lücke",2025,1,line(0,0,10,0,8));
gap.points.slice(4).forEach(p=>p.t+=100000);
near(report(gap).uncertainM,60);
assert.equal(report(gap).newM,0);
assert.equal(report(gap).routes.length,2);
const paused=ride("pausiert",2025,0,line(0,0,10,0,8));
paused.pauses=[{start:paused.points[3].t,end:paused.points[4].t}];
assert.equal(report(paused).routes.length,2);
assert.equal(report(paused).newM,0);
const jump=ride("Sprung",2025,0,[...line(0,0,10,0,4),...line(1000,0,10,0,4)]);
assert.equal(report(jump).routes.length,2);
assert.equal(report(jump).newM,0);
const missing=ride("leer",2025,6,[]);
const result=report(branch,missing,shifted,old,parallel,{...branch,status:"recording"},{...branch,activityType:"running"});
near(result.card.totalM,720);
near(result.card.longestM,240);
assert.deepEqual(result.card.activeMonths,[0,1,3]);
assert.equal(result.missing,1);
assert.equal(result.rideCount,4);
assert.equal(result.previousTracks,1);
assert.equal(report(branch).previousTracks,0);
assert.equal(report(missing).card.totalM,null);
assert.equal(report(ride("Stillstand",2025,0,[[0,0],[0,0]])).card.totalM,0);
assert.equal(Wrapped.analyzeYear([old],2023).rideCount,0);
assert.equal(Wrapped.rideYear({...old,status:"paused"}),null);
assert.equal(Wrapped.rideYear({...old,endedAt:undefined}),null);
const midnight=new Date(2026,0,1).getTime();
assert.equal(Wrapped.rideYear({...old,startedAt:midnight-1,endedAt:midnight+10}),2025);
assert.equal(Wrapped.rideYear({...old,startedAt:midnight}),2026);
assert.deepEqual(Object.keys(result.card).sort(),["activeMonths","longestM","totalM","year"]);
const elevationRows=Array.from({length:11},(_,i)=>({distanceM:i*10,segment:0,altitude:i===5?400:100,time:i*1000}));
const filtered=elevation.process(elevationRows);
assert.equal(filtered.spikesRejected,1);
near(filtered.coveredM,80);
assert.equal(filtered.medianAccuracy,null);
const partial=ride("Höhenlücke",2025,0,line(0,0,10,0,11));
partial.points.forEach((p,i)=>{p.alt=100;p.altAccuracy=i===4?40:5;});
partial.points[8].alt=null;
near(Core.analyze(partial).elevationProfile.coveredM,60);
const duplicatePause={...paused,pauses:[...paused.pauses,...paused.pauses]};
near(Core.analyze(duplicatePause).elapsedSeconds,12);
near(Core.analyze({...duplicatePause,pausedMs:0}).elapsedSeconds,12);
assert.equal(filtered.missingAccuracyCount,10);
console.log("Jahreskennzahlen, GPS-Vergleich, Exportfelder, Profilabdeckung und Pausenzeiten geprüft");
